const stateLabelByValue = Object.fromEntries(states.map(({ value, label }) => [value, label]));
function stateValueFor(value) {
  const normalized = String(value || "").trim().toLocaleLowerCase("hi-IN");
  const aliases = {
    "uttar pradesh": "uttar-pradesh",
    "उत्तर प्रदेश": "uttar-pradesh",
    "मध्य प्रदेश": "madhya-pradesh",
    "madhya pradesh": "madhya-pradesh",
    "झारखंड": "jharkhand",
    "राजस्थान": "rajasthan",
    "बिहार": "bihar",
  };
  return states.find((state) => state.value === normalized || state.label.toLocaleLowerCase("hi-IN") === normalized)?.value || aliases[normalized] || "";
}
function stateForDistrict(district) {
  const value = String(district || "").trim().toLowerCase();
  return Object.keys(districtsByState).find((state) => districtsByState[state].some((item) => item.toLowerCase() === value)) || "";
}

function districtBelongsToState(state, district) {
  const stateValue = stateValueFor(state);
  return Boolean(stateValue && districtsByState[stateValue]?.includes(String(district || "").trim()));
}

